"""Generates an AlphaGenome (AG) finetuning configuration file.

This script maps data modalities to directories, retrieves associated BigWig 
files, strips specified tags from filenames, and integrates precomputed non-zero 
track means to format the final YAML head configurations required for 
AlphaGenome finetuning.
"""
from __future__ import annotations

import argparse
import pandas as pd

from cardiomics_s2f.preprocessing.ag_targets_config import build_targets_config, write_targets_config


def get_parser() -> argparse.ArgumentParser:
    """Creates and configures the argument parser for the config generator.
    
    This function is isolated to allow Sphinx extensions (`sphinxarg.ext`) 
    to auto-generate CLI documentation natively without executing the script.

    Returns:
        argparse.ArgumentParser: The configured argument parser object.
    """
    parser = argparse.ArgumentParser(description="Generate AG finetuning YAML config")
    
    # Core I/O arguments
    parser.add_argument("--data_dir", type=str, required=True, 
                        help="Base path to bigwig input data directories")
    parser.add_argument("--config_prefix", type=str, default="config.yaml", 
                        help="Path and name of the output YAML file")
    
    # Using nargs='+' allows the user to pass multiple folders like: --modality_folders ATAC RNA
    parser.add_argument("--modality_folders", type=str, nargs='+', required=True, 
                        help="List of subfolders in data_dir corresponding to modalities. Must contain ATAC, RNA, or CutnTag in name.")
    parser.add_argument("--nonzero_means", type=str, default="input_data/metadata/bw_nonzero_means.csv",  
                        help="CSV file generated by 00_compute_nonzero_means_per_bw.sh")
    
    # Optional filtering argument
    parser.add_argument("--norm_tag", type=str, default=None, 
                        help="Tag to filter and clean normalized bigwig files (default: None)")
    
    return parser


def main(args: argparse.Namespace) -> None:
    """Executes the YAML configuration generation pipeline.

    Loads the precomputed non-zero track means, builds the targets
    configuration with `build_targets_config` and writes it to YAML.

    Args:
        args (argparse.Namespace): Parsed command-line arguments containing 
            directory paths, modality targets, and tag filters.

    Raises:
        ValueError: If a provided modality folder name does not correspond 
            to a recognized modality (CutnTag, ATAC, or RNA).
        AssertionError: If an input `.bw` file is missing from the precomputed 
            nonzero track means CSV.
    """
    nonzero_means = pd.read_csv(args.nonzero_means)
    config = build_targets_config(
        args.data_dir, args.modality_folders, nonzero_means, norm_tag=args.norm_tag
    )
    write_targets_config(config, args.config_prefix)


if __name__ == "__main__":
    parser = get_parser()
    args = parser.parse_args()
    main(args)